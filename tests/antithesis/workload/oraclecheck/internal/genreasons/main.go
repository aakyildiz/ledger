// Command genreasons writes oraclecheck/outcome_reasons.go from the protocol
// fixture's definitive reason list (one reason per line), so the oracle embeds
// exactly the list the driver reads. Run through `go generate` in oraclecheck;
// bin/oracle/reasons_test.go checks the result.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

func main() {
	in := flag.String("in", "", "definitive_reasons.txt")
	out := flag.String("out", "", "generated Go file")
	flag.Parse()

	data, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	src, err := Render(data)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// Render returns the generated file for a reason list.
func Render(list []byte) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by oraclecheck/internal/genreasons from\n")
	b.WriteString("// tests/antithesis/hegel/protocol-fixtures/core/definitive_reasons.txt. DO NOT EDIT.\n\n")
	b.WriteString("package oraclecheck\n\n")
	b.WriteString("// definitiveReasonList is D of DESIGN §4.5, sorted.\n")
	b.WriteString("var definitiveReasonList = []string{\n")
	for _, line := range strings.Split(string(list), "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		fmt.Fprintf(&b, "\t%q,\n", line)
	}
	b.WriteString("}\n\n")
	b.WriteString("var definitiveReasons = func() map[string]bool {\n\tm := make(map[string]bool, len(definitiveReasonList))\n\tfor _, r := range definitiveReasonList {\n\t\tm[r] = true\n\t}\n\n\treturn m\n}()\n")

	return format.Source(b.Bytes())
}
